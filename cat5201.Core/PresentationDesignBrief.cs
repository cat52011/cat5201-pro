namespace Cat5201
{
    /// <summary>
    /// 文件技能版的視覺設計規約。依語意選擇風格，不以「設計」關鍵字把軟體設計誤判成藝術主題。
    /// 此規約指導生成與視覺自查；不是本機版面驗證器，也不改變內建快速版的能力。
    /// </summary>
    public static class PresentationDesignBrief
    {
        public static string Build(string? savedDirection)
        {
            string direction = string.IsNullOrWhiteSpace(savedDirection)
                ? "依主題與受眾自動設計；視覺設計、藝術、建築、攝影、時尚與展覽主題，優先採雜誌／藝術展覽風格。"
                : savedDirection.Trim();

            return "【簡報視覺設計任務】\n" +
                   "本次明確指定的風格、品牌、範本與無圖要求優先，其次採用下列保存的視覺方向，再採預設設計。\n" +
                   "保存的視覺方向：" + direction + "\n\n" +
                   Instructions;
        }

        public const string Instructions = """
【先規劃視覺，再製作投影片】
1. 依主要內容判斷題材、受眾與情境，選擇一套有理由的藝術方向。不要只因題目出現「系統設計」就套藝術展風格。藝術／設計題材可採編輯式網格、不對稱構圖、大字、作品主視覺與充足留白；技術／研究題材以結構圖、流程、比較與資料視覺化為主；商業題材強調產品與證據。不要全都套深藍科技模板。
2. 動手前在工作目錄寫 design-plan.md：先列主題、色盤（背景／文字／一至兩個重點色）、字體與字級層次、網格，再逐頁列出目的、核心訊息、版面、主要視覺、素材依據及講者備註。這是內部製作材料，不放進觀眾投影片。
3. 每頁先決定觀眾要「看見」的資訊關係：過程用流程圖、比較用對照構圖、結構用架構圖、有實際數列才用圖表，作品／產品用主視覺；不要把原本的段落逐條裝進矩形卡片。無數據時不得編造數字、百分比、趨勢或裝飾性假圖表。

【構圖與節奏】
- 預設 16:9。封面用主視覺與標題建立識別；內容頁依任務選擇大圖留白、圖文分割、全幅圖像、關係圖、對照、資料圖表、重點引言等，保持同一套視覺語言。短簡報不為湊版型而加頁；較長簡報避免連續三頁相同構圖。
- 設計／藝術題材可加強尺度差、裁切、非對稱與有意識的色面；藝術性來自內容與構圖的關係，不能只靠漸層、陰影、圓角卡片或散落的裝飾圓形。
- 一頁一個焦點。多數適合的內容頁讓有意義的視覺佔約半頁以上，文字負責解讀。主標約 32–48 pt、重點字可更大、內文約 22–28 pt，實際依語言與版面調整。保留清楚的對齊、邊距與對比。
- 內文優先用短標籤與一句解釋；一般頁以 2–4 個短重點為上限方向，詳述、論證與補充放講者備註。來源頁可例外。內容太多應改構圖或依指定頁數重新精煉，不要縮小字體硬塞、截斷必要資訊，或把完整報告搬上投影片。
- 標題直接點出主題或有證據支持的發現。議程頁、章節分隔頁與「下一步」只有在敘事需要時才加入，不固定套用。避免每頁重複大標題帶、頁尾標語及同一張裝飾圖。

【圖像與可編輯性】
- 有可用素材時用主題相關圖片；不得假裝取得未提供的照片、作品、產品截圖或品牌素材。工具沒有圖片或網路能力時，用程式繪製與內容相關的示意圖、向量插畫或關係圖，不要因此退回全文字，也不要使用破圖或圖片占位符。
- 示意圖不可冒充真實事件照片或實測結果；需要真實作品但缺素材時，明示缺少素材，避免虛構作品內容。
- 圖片保留比例，可有意識地裁切；證據截圖不可裁掉關鍵內容。文字、主要形狀與圖表盡量保持可編輯，不把整張投影片扁平化成圖片。中文需使用含中文字形的字體並設定 East Asian 字型。

【交付前視覺自查】
產出後渲染每頁並建立 contact sheet 檢查全套節奏，再逐頁檢查可讀性、溢出、重疊、中文缺字、圖片比例及圖表與來源的一致性。若多數內容頁仍是「標題＋條列」或重複卡片，重做主要構圖再交付；使用者明確指定純文字／固定範本時尊重其要求。修正後重新匯出 PPTX 與對應 PDF。
只有實際完成渲染檢查，才可在交付說明宣稱已視覺檢查；無法渲染時明確說明限制，不宣稱品質通過。
""";
    }
}
